    public static string Translate(string sourceText)
    {
        if (Exact.TryGetValue(sourceText, out var spanish))
        {
            return spanish;
        }

        var translated = sourceText;
        foreach (var pair in EmbeddedExact)
        {
            translated = translated.Replace(pair.Key, pair.Value, StringComparison.Ordinal);
        }

        foreach (var (polish, replacement) in Replacements)
        {
            translated = translated.Replace(polish, replacement, StringComparison.Ordinal);
        }

        // Teksty techniczne (nazwy formatów, skróty i ścieżki), których nie ma
        // w katalogu, pozostają bez zmian zamiast przełączać fragment interfejsu
        // na angielski. Dzięki temu każda dynamiczna polska część jest tłumaczona
        // przez spójny katalog hiszpański.
        return translated;
    }
