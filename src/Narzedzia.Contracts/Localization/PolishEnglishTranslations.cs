    public static string Translate(string polishText)
    {
        if (Exact.TryGetValue(polishText, out var exact))
        {
            return exact;
        }

        var translated = polishText;
        foreach (var pair in EmbeddedExact)
        {
            translated = translated.Replace(pair.Key, pair.Value, StringComparison.Ordinal);
        }

        foreach (var (polish, english) in Replacements)
        {
            translated = translated.Replace(polish, english, StringComparison.Ordinal);
        }

        return translated;
    }
